var CACHE = 'momo-' + VERSION;
var FONTS = 'momo-fonts';            /* Google Fonts (Baloo 2, Nunito); not tied to a build */
var FONT_CSS = 'https://fonts.googleapis.com/css2?family=Baloo+2:wght@600;700;800&family=Nunito:wght@600;700;800&display=swap';

function fetchFresh(url) {
  /* cache:'reload' skips the browser's own HTTP cache, which could hold an older copy of a file */
  return fetch(new Request(url, { cache: 'reload' })).then(function (r) {
    if (!r.ok) throw new Error(url + ' ' + r.status);
    return r;
  });
}

/* Fonts are nice to have, never a reason to fail the install. Only the latin faces are kept (all 7 languages' Latin text, plus the digits). */
function precacheFonts() {
  return caches.open(FONTS).then(function (fc) {
    return fetch(FONT_CSS).then(function (r) {
      if (!r.ok) throw 0;
      return fc.put(FONT_CSS, r.clone()).then(function () { return r.text(); });
    }).then(function (css) {
      var jobs = [], re = /\/\*\s*(latin|latin-ext|vietnamese)\s*\*\/\s*@font-face\s*\{[^}]*?url\(([^)]+)\)/g, m;
      while ((m = re.exec(css))) jobs.push(m[2]);
      return Promise.all(jobs.map(function (u) {
        return fc.match(u).then(function (hit) { return hit || fetch(u).then(function (fr) { return fr.ok ? fc.put(u, fr) : 0; }); });
      }));
    });
  }).catch(function () {});
}

self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) {
    return Promise.all(ASSETS.map(function (u) {
      return fetchFresh(u).then(function (r) { return c.put(u, r); });
    })).then(function () {
      /* the index.html we just stored must be the build this worker was made for, or the deploy was caught half-way: try again later */
      return c.match('./').then(function (r) { return r.text(); }).then(function (t) {
        var m = /<meta name="build" content="([^"]+)"/.exec(t);
        if (BUILD && (!m || m[1] !== BUILD)) throw new Error('build mismatch');
      });
    });
  }).catch(function (err) {
    return caches.delete(CACHE).then(function () { throw err; });
  }).then(precacheFonts));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('momo-') === 0 && k !== CACHE && k !== FONTS; })
      .map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('message', function (e) {
  if (e.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);

  if (url.origin === self.location.origin) {
    if (url.pathname.indexOf('/_vercel/') === 0) return;                      /* analytics: straight to the network, quietly fails offline */
    if (url.pathname === '/sw.js') return;
    if (req.cache === 'no-store' || url.searchParams.has('b')) return;       /* the page's "is there a newer build?" check must really ask the server */
    e.respondWith(caches.open(CACHE).then(function (c) {
      return c.match(req, { ignoreSearch: true }).then(function (hit) {
        if (hit) return hit;
        if (req.mode === 'navigate') return c.match('./');
        return fetch(req);
      });
    }));
    return;
  }

  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(caches.open(FONTS).then(function (fc) {
      return fc.match(req.url).then(function (hit) {
        var net = fetch(req).then(function (r) { if (r.ok) fc.put(req.url, r.clone()); return r; });
        return hit || net;
      });
    }));
  }
});
